# every material class in the scene, mapped to one of the families above
USE = {
    "m-cab": "navy", "m-rack": "navy",
    "m-forklift": "orange", "m-beam": "orange", "m-safety": "orange", "m-amber": "orange",
    "m-alu": "light", "m-steel": "light", "m-chrome": "light", "m-rim": "light", "m-concrete": "light", "st-wall": "light", "st-door": "light",
    "m-truss": "grey", "st-drum": "grey",
    "m-chassis": "graph", "m-tyre": "graph", "m-dark": "graph", "m-seat": "graph", "m-fork": "graph", "m-bumper": "graph",
    "m-kraft": "kraft", "m-card": "kraft",
    "m-wood": "wood", "m-deck": "wood", "st-floor": "wood", "m-trunk": "wood",
    "st-yard": "yard",
}

def rules(scope, fam):
    out = []
    for name, f in USE.items():
        top, body, shade, deep, edge = fam[f]
        sel = f"{scope} .{name}"
        out.append(f"{sel}>.iso-fill,{sel}>.st-face{{fill:{body}}}")
        out.append(f"{sel}>.iso-top{{fill:{top}}}")
        out.append(f"{sel}>.iso-shade{{fill:{shade}}}")
        out.append(f'{sel}>.iso-shade[data-shade="2"],{sel}>.iso-shade[data-shade="3"]{{fill:{deep}}}')
        out.append(f"{sel}>:is(.iso-edge,.iso-line){{stroke:{edge}}}")
    return out

